export function getFieldLabel(field: string, gender: 'brother' | 'sister'): string {
  const labels = gender === 'brother' ? BROTHER_FIELD_LABELS : SISTER_FIELD_LABELS
  return labels[field] ?? field
    .replace(/_/g, ' ')
    .replace(/\b\w/g, l => l.toUpperCase())
}

